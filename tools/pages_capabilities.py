def capability_layout(hero, intro, sections, side, cta):
    section_html = []
    for i, (anchor, title, body) in enumerate(sections, 1):
        section_html.append(
            f'<div class="page-section" id="{anchor}">'
            f'<div class="page-section__head"><h2 class="page-section__title">{title}</h2>'
            f'<span class="page-section__num">{i:02d}</span></div>{body}</div>'
        )
    side_html = side_nav(*side)
    return f"""{hero}
<section class="section section--paper">
<div class="container content-grid">
<div class="content-main">
{prose(intro)}
{''.join(section_html)}
{cta}
</div>
{side_html}
</div>
</section>"""


